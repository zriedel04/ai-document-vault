"""Build the synthetic demo corpus, its manifest and the public eval set.

    uv run python build.py            write demo/corpus/, demo/corpus/manifest.json,
                                      demo/corpus/references/ and eval/public/questions.yaml
    uv run python build.py --check    build in memory and fail if the committed files differ
                                      (used by CI on Linux, where the pinned libraries give
                                      byte-identical output)

Everything is fictional. The output is deterministic: running the build twice gives the same bytes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import yaml

import content_courses
import content_extra
import content_media
import content_project
import references
from model import Document
from questions import Question, build_questions
from render import render_docx, render_image, render_pdf_scan, render_pdf_text

REPO = Path(__file__).resolve().parents[2]
CORPUS = REPO / "demo" / "corpus"
QUESTIONS = REPO / "eval" / "public" / "questions.yaml"

QUESTIONS_HEADER = """\
# Public retrieval eval set for the synthetic demo corpus (demo/corpus/).
# GENERATED by demo/generate/build.py from demo/generate/questions.py. Do not edit by hand.
# All people, courses and documents are fictional. See eval/README.md for the format.
"""


def all_documents() -> list[Document]:
    docs = [
        *content_courses.DOCS,
        *content_project.DOCS,
        *content_media.DOCS,
        *content_extra.DOCS,
    ]
    paths = [d.path for d in docs]
    if len(paths) != len(set(paths)):
        raise ValueError("duplicate document path in the corpus definition")
    return sorted(docs, key=lambda d: d.path)


def render(doc: Document) -> bytes:
    match doc.kind:
        case "pdf_text":
            return render_pdf_text(doc)
        case "pdf_scan":
            return render_pdf_scan(doc)
        case "docx":
            return render_docx(doc)
        case "txt" | "md" | "csv":
            return doc.text.encode("utf-8")
        case "png" | "jpg":
            return render_image(doc)
    raise ValueError(f"unknown kind {doc.kind!r}")


def manifest_entry(doc: Document, data: bytes) -> dict[str, object]:
    entry: dict[str, object] = {
        "path": doc.path,
        "kind": doc.kind,
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "pages": len(doc.page_texts()) if doc.paginated else None,
        "needs_ocr": doc.kind in ("pdf_scan", "png", "jpg"),
    }
    if doc.exact_duplicate_of:
        entry["exact_duplicate_of"] = doc.exact_duplicate_of
    if doc.near_duplicate_of:
        entry["near_duplicate_of"] = doc.near_duplicate_of
    if doc.note:
        entry["note"] = doc.note
    return entry


def question_entry(q: Question) -> dict[str, object]:
    entry: dict[str, object] = {
        "id": q.id,
        "question": q.question,
        "category": q.category,
        "answerable": q.answerable,
        "answer": q.answer,
        "sources": [{"path": src.path, "page": src.page, "quote": src.quote} for src in q.sources],
    }
    if q.alternatives:
        entry["alternatives"] = [
            {"path": src.path, "page": src.page, "quote": src.quote} for src in q.alternatives
        ]
    if q.distractors:
        entry["distractors"] = list(q.distractors)
    if q.find_document:
        entry["find_document"] = True
    return entry


def build_outputs() -> dict[str, bytes]:
    """Return every generated file as {path relative to the repository: content}."""
    files: dict[str, bytes] = {}
    entries = []
    for doc in all_documents():
        data = render(doc)
        files[f"demo/corpus/{doc.path}"] = data
        entries.append(manifest_entry(doc, data))
        # Reference texts for the OCR and PDF spikes. They are not documents: the manifest does
        # not list them (see references.py).
        for path, text in references.reference_files(doc).items():
            files[f"demo/corpus/{path}"] = text.encode("utf-8")
    manifest = {
        "description": "Synthetic demo corpus. Every person, course and document is fictional.",
        "generated_by": "demo/generate/build.py",
        "documents": entries,
    }
    files["demo/corpus/manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    questions = [question_entry(q) for q in build_questions()]
    dumped = yaml.safe_dump(
        {"questions": questions}, sort_keys=False, allow_unicode=True, width=100
    )
    files["eval/public/questions.yaml"] = (QUESTIONS_HEADER + dumped).encode()
    return files


def write(files: dict[str, bytes], root: Path) -> None:
    for relative, data in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def check(files: dict[str, bytes]) -> int:
    problems = []
    for relative, data in files.items():
        committed = REPO / relative
        if not committed.is_file():
            problems.append(f"missing: {relative}")
        elif committed.read_bytes() != data:
            problems.append(f"differs: {relative}")
    expected = {p for p in files if p.startswith("demo/corpus/")}
    for found in CORPUS.rglob("*"):
        relative = found.relative_to(REPO).as_posix()
        if found.is_file() and relative not in expected:
            problems.append(f"unexpected file: {relative}")
    if problems:
        print("The committed corpus does not match the generator:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        print(
            "Run `uv run python build.py` in demo/generate and commit the result.", file=sys.stderr
        )
        return 1
    print(f"corpus matches the generator ({len(files)} files)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    files = build_outputs()
    if args.check:
        return check(files)
    # Remove stale generated files so deleted documents do not linger.
    if CORPUS.exists():
        for old in sorted(CORPUS.rglob("*"), reverse=True):
            if old.is_file():
                old.unlink()
            elif not any(old.iterdir()):
                old.rmdir()
    QUESTIONS.parent.mkdir(parents=True, exist_ok=True)
    write(files, REPO)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
